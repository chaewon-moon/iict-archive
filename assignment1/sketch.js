function setup() {
  createCanvas(400, 600);
}

function draw() {
  background(178, 172, 165);
   // 2. 보도블록 (오른쪽 영역)
  stroke(120);
  strokeWeight(3);
  
  // 세로선
  line(250, 0, 250, 600);
  line(300, 0, 300, 600);
  line(350, 0, 350, 600);

  // 가로선
  line(200, 100, 400, 100);
  line(200, 200, 400, 200);
  line(200, 300, 400, 300);
  line(200, 400, 400, 400);
  line(200, 500, 400, 500);

  // 3. 벤치 나무 판자 (왼쪽 영역)
  stroke(0);         // 테두리 검은색
  strokeWeight(2);
  fill(241, 170, 178); // 붉은 벤치 색상

  rect(0, 0, 50, 600);
  rect(60, 0, 50, 600);
  rect(120, 0, 50, 600);
  rect(180, 0, 50, 600);

  // 4. 벤치 나뭇결/얼룩 느낌
  stroke(50);
  strokeWeight(1);
  fill(80, 66, 58);

  line(10, 100, 35, 120);
  line(75, 250, 95, 230);
  line(130, 400, 155, 420);
  ellipse(25, 300, 15, 10);
  ellipse(145, 150, 10, 15);

  // 5. 커피 컵 그리기 (입체감 추가)

  // A. 컵 밑면 (바닥에 닿는 작은 타원)
  stroke(0);
  strokeWeight(2);
  fill(220); // 약간 어두운 흰색(그림자 느낌)
  ellipse(140, 340, 50, 25);

  // B. 컵 옆면 (몸통 사다리꼴 - quad(x1, y1, x2, y2, x3, y3, x4, y4))
  // 윗면 양끝과 밑면 양끝을 연결
  noStroke();      // 옆면과 윗면 경계선 제거
  fill(255);       // 흰색
  quad(100, 310, 180, 310, 165, 340, 115, 340);
  
  // 옆면 테두리 선만 따로 그리기
  stroke(0);
  strokeWeight(2);
  line(100, 310, 115, 340); // 왼쪽 기울어진 선
  line(180, 310, 165, 340); // 오른쪽 기울어진 선

  // C. 컵 윗면 (기존 흰색 윗면)
  fill(255);
  ellipse(140, 310, 80, 40); // 세로 길이를 줄여 비스듬한 원으로 변경

  // D. 컵 내부 음료 (어두운 갈색)
  noStroke();
  fill(50, 30, 20);
  ellipse(140, 310, 60, 30);

  // E. 투명 뚜껑 (기존 원보다 위쪽으로 록하게 표현)
  stroke(180);
  strokeWeight(1.5);
  fill(255, 255, 255, 120);
  ellipse(140, 305, 70, 45);

  // F. 노란색 빨대
  stroke(0);
  strokeWeight(1);
  fill(255, 230, 100);
  rect(132, 290, 6, 18);
}
